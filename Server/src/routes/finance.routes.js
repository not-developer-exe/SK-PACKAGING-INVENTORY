const express = require('express');
const router = express.Router();
const { protect } = require('../middlewares/auth.middleware');
const { requireRole } = require('../middlewares/role.middleware');
const { listAccounts, createAccount, updateAccount, deactivateAccount, listTransactions, createTransaction, getInvoiceBankDetails } = require('../controllers/finance.controller');
router.use(protect);
router.get('/accounts', listAccounts);
router.post('/accounts', requireRole('admin'), createAccount);
router.put('/accounts/:id', requireRole('admin'), updateAccount);
router.delete('/accounts/:id', requireRole('admin'), deactivateAccount);
router.get('/transactions', listTransactions);
router.post('/transactions', createTransaction);
router.get('/invoice-bank-details', getInvoiceBankDetails);
module.exports = router;
